// typegen derives the browser contract from Go reflection and JSON tags.
// It deliberately contains no second list of model fields.
package main

import (
	"blackbox/internal/protocol"
	"blackbox/internal/sim"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
)

func main() {
	root, err := os.Getwd()
	if err != nil {
		panic(err)
	}
	for {
		if _, err = os.Stat(filepath.Join(root, "go.mod")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if parent == root {
			panic("backend/go.mod not found")
		}
		root = parent
	}
	output := filepath.Join(root, "../frontend/src/generated/protocol.ts")
	collected := map[string]reflect.Type{}
	var typeName func(reflect.Type) string
	typeName = func(t reflect.Type) string {
		if t.Kind() == reflect.Pointer {
			return typeName(t.Elem())
		}
		if t.Kind() == reflect.Struct {
			if _, ok := collected[t.Name()]; !ok {
				collected[t.Name()] = t
				for i := 0; i < t.NumField(); i++ {
					typeName(t.Field(i).Type)
				}
			}
			return t.Name()
		}
		switch t.Kind() {
		case reflect.Bool:
			return "boolean"
		case reflect.String:
			return "string"
		case reflect.Array, reflect.Slice:
			return "Array<" + typeName(t.Elem()) + ">"
		default:
			return "number"
		}
	}
	typeName(reflect.TypeOf(protocol.Message{}))
	typeName(reflect.TypeOf(protocol.Command{}))
	keys := make([]string, 0, len(collected))
	for k := range collected {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("// Generated by backend/cmd/typegen. Do not edit; run npm run types.\n// Integer quantities use 1000 units; ratios/skills use 10000 basis points.\n\n")
	fmt.Fprintf(&b, "export const PROTOCOL_VERSION = %d as const;\n", protocol.Version)
	for _, name := range keys {
		t := collected[name]
		fmt.Fprintf(&b, "export interface %s {\n", name)
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			if tag[0] == "-" {
				continue
			}
			n := tag[0]
			if n == "" {
				n = f.Name
			}
			optional := ""
			if strings.Contains(f.Tag.Get("json"), "omitempty") {
				optional = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", n, optional, typeName(f.Type))
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("export const GOODS = [")
	for i := 0; i < sim.GOOD_COUNT; i++ {
		fmt.Fprintf(&b, "%q,", sim.GoodName(i))
	}
	b.WriteString("] as const;\n")
	b.WriteString("export const ACTIVITIES = [")
	for i := 0; i < sim.DECISION_CANDIDATES; i++ {
		fmt.Fprintf(&b, "%q,", sim.ActivityName(i))
	}
	b.WriteString("] as const;\n")
	b.WriteString("export const ROLES = [")
	for i := 0; i < sim.ROLE_COUNT; i++ {
		fmt.Fprintf(&b, "%q,", sim.RoleName(i))
	}
	b.WriteString("] as const;\n")
	if err = os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		panic(err)
	}
	if err = os.WriteFile(output, []byte(b.String()), 0644); err != nil {
		panic(err)
	}
	fmt.Println(output)
}
